function annualWindows(
  start: [number, number],
  end: [number, number],
  peak: [number, number, number, number],
  years = [2025, 2026, 2027],
) {
  return years.map((year) => {
    const wraps = end[0] < start[0] || (end[0] === start[0] && end[1] < start[1]);
    const peakWraps = peak[0] < start[0];
    const endYear = wraps ? year + 1 : year;
    const peakYear = peakWraps ? year + 1 : year;
    const pad = (n: number) => String(n).padStart(2, "0");
    return {
      seasonKey: String(year),
      start: `${year}-${pad(start[0])}-${pad(start[1])}`,
      peak: [`${peakYear}-${pad(peak[0])}-${pad(peak[1])}`, `${peakYear}-${pad(peak[2])}-${pad(peak[3])}`] as [string, string],
      end: `${endYear}-${pad(end[0])}-${pad(end[1])}`,
    };
  });
}

